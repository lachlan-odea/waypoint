// The Waypoint logo (design system §3): three staggered, fully rounded bars —
// a plan moving left to right, top to bottom, start to finish. The last bar,
// the destination, is the only coloured element.
//
// Construction on a 48-unit grid: bar height x = 8, radius x/2; rows at
// y 8 · 20 · 32; bars at x5 w22 · x13 w24 · x23 w20, each stepping right by
// one x. Wordmark: DM Sans Bold, −0.03em; cap height equals the bar stack
// (32 units), baseline on the last bar's bottom edge (y = 40), 12-unit gap.
//
// Only these four colourways exist. Never retype, recolour, reorder,
// stretch, rotate or square off the bars — use this component or the SVGs
// in public/logos/ (generated by scripts/make-logos.mjs from the same
// geometry).
//
// The wordmark is rendered as SVG <text> in DM Sans, not as outlines: we
// can't outline a web font at build time here, and the page already loads
// DM Sans. The static SVGs in public/logos/ carry the same caveat.

export type LogoColor = "blue" | "white" | "mono-blue" | "mono-white";
export type LogoVariant = "horizontal" | "stacked" | "mark";

const COLORWAYS: Record<LogoColor, { main: string; destination: string }> = {
  blue: { main: "#1D1765", destination: "#371EE1" },
  white: { main: "#FFFFFF", destination: "#B7B3FF" },
  "mono-blue": { main: "#1D1765", destination: "#1D1765" },
  "mono-white": { main: "#FFFFFF", destination: "#FFFFFF" },
};

// Bar geometry, in grid units.
const MARK_BARS = [
  { x: 5, y: 8, w: 22 },
  { x: 13, y: 20, w: 24 },
  { x: 23, y: 32, w: 20 },
] as const;
const BAR_H = 8;
const BAR_R = 4;

// DM Sans Bold has a cap height of ~0.7em, so a 32-unit cap height needs a
// font size of ~45.7 units. The wordmark then runs ~194 units wide.
const WORD_FONT = 45.7;
const WORD_WIDTH = 194;
const GAP = 12;
const FONT = '"DM Sans", ui-sans-serif, system-ui, sans-serif';

function Bars({ color }: { color: LogoColor }) {
  const cw = COLORWAYS[color];
  return (
    <>
      {MARK_BARS.map((b, i) => (
        <rect
          key={i}
          x={b.x}
          y={b.y}
          width={b.w}
          height={BAR_H}
          rx={BAR_R}
          fill={i === MARK_BARS.length - 1 ? cw.destination : cw.main}
        />
      ))}
    </>
  );
}

export function WaypointMark({
  size = 24,
  color = "blue",
  className,
  title = "Waypoint",
}: {
  size?: number;
  color?: LogoColor;
  className?: string;
  title?: string;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 48 48"
      role="img"
      aria-label={title}
      className={className}
    >
      <title>{title}</title>
      <Bars color={color} />
    </svg>
  );
}

export function WaypointLogo({
  variant = "horizontal",
  color = "blue",
  height = 26,
  className,
  title = "Waypoint",
}: {
  variant?: LogoVariant;
  color?: LogoColor;
  // Rendered height in CSS pixels. Minimums per the spec: 20px horizontal,
  // 16px mark.
  height?: number;
  className?: string;
  title?: string;
}) {
  const cw = COLORWAYS[color];
  if (variant === "mark") {
    return <WaypointMark size={height} color={color} className={className} title={title} />;
  }
  if (variant === "stacked") {
    // Mark centred above the wordmark. Box 200 × 100: mark at the top,
    // wordmark (cap height 24) with its baseline at y = 88.
    const fs = 34.3;
    const vbW = 200;
    const vbH = 100;
    return (
      <svg
        height={height}
        width={(height * vbW) / vbH}
        viewBox={`0 0 ${vbW} ${vbH}`}
        role="img"
        aria-label={title}
        className={className}
      >
        <title>{title}</title>
        <g transform={`translate(${(vbW - 48) / 2} 0)`}>
          <Bars color={color} />
        </g>
        <text
          x={vbW / 2}
          y={88}
          textAnchor="middle"
          fontFamily={FONT}
          fontWeight={700}
          fontSize={fs}
          letterSpacing="-0.03em"
          fill={cw.main}
        >
          Waypoint
        </text>
      </svg>
    );
  }
  // Horizontal (default): mark, 12-unit gap, wordmark on the last bar's
  // baseline.
  const vbW = 48 + GAP + WORD_WIDTH + 6;
  const vbH = 48;
  return (
    <svg
      height={height}
      width={(height * vbW) / vbH}
      viewBox={`0 0 ${vbW} ${vbH}`}
      role="img"
      aria-label={title}
      className={className}
    >
      <title>{title}</title>
      <Bars color={color} />
      <text
        x={48 + GAP}
        y={40}
        fontFamily={FONT}
        fontWeight={700}
        fontSize={WORD_FONT}
        letterSpacing="-0.03em"
        fill={cw.main}
      >
        Waypoint
      </text>
    </svg>
  );
}
